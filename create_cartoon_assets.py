def create_confetti():
    im = Image.new("RGBA", (400, 400), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    colors = ["#EF4444", "#F59E0B", "#10B981", "#3B82F6", "#EC4899", "#8B5CF6"]
    import random
    random.seed(42)
    for _ in range(60):
        x = random.randint(10, 380)
        y = random.randint(10, 380)
        col = random.choice(colors)
        sz = random.randint(8, 18)
        shape = random.choice(["rect", "circle", "star"])
        if shape == "rect":
            d.rectangle([x, y, x + sz, y + sz//2], fill=col)
        elif shape == "circle":
            d.ellipse([x, y, x + sz, y + sz], fill=col)
        else:
            d.polygon([(x, y - sz), (x + sz//2, y), (x, y + sz), (x - sz//2, y)], fill=col)
    im.save(os.path.join(OUT_DIR, "item_confetti.png"))
    print("Created item_confetti.png")

